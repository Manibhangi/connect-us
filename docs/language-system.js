    /* =====================================================
       DYNAMIC ALERTS
    ===================================================== */

    function translateDialogMessage(
        message
    ) {

        const raw =
            String(
                message ?? ""
            );


        const key =
            keyFromEnglish(
                raw
            );


        return key
            ? t(key)
            : raw;
    }


    const nativeAlert =
        window.alert.bind(
            window
        );


    window.alert =
        function (message) {

            nativeAlert(
                translateDialogMessage(
                    message
                )
            );
        };


    if (window.confirm) {

        const nativeConfirm =
            window.confirm.bind(
                window
            );


        window.confirm =
            function (message) {

                return nativeConfirm(
                    translateDialogMessage(
                        message
                    )
                );
            };
    }


    /* =====================================================
       DYNAMIC CONTENT OBSERVER
    ===================================================== */

    function installObserver() {

        if (
            !document.body ||
            window.__connectUsLanguageObserverInstalled
        ) {

            return;
        }


        window.__connectUsLanguageObserverInstalled =
            true;


        let scheduled =
            false;


        const observer =
            new MutationObserver(
                function (mutations) {

                    const relevant =
                        mutations.some(
                            function (mutation) {

                                return (
                                    mutation.addedNodes
                                        .length > 0
                                );
                            }
                        );


                    if (
                        !relevant ||
                        scheduled
                    ) {

                        return;
                    }


                    scheduled =
                        true;


                    requestAnimationFrame(
                        function () {

                            scheduled =
                                false;


                            setupSettingsControls();


                            applyLanguage();

                        }
                    );
                }
            );


        observer.observe(
            document.body,
            {
                childList: true,
                subtree: true
            }
        );
    }


